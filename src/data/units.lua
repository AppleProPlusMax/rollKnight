function M.rollRarity(prismBonus)
  local weights = {
    normal = M.RARITIES.normal.weight,
    rare   = M.RARITIES.rare.weight,
    epic   = M.RARITIES.epic.weight + (prismBonus or 0),
    prism  = M.RARITIES.prism.weight + (prismBonus or 0),
  }
  local total = weights.normal + weights.rare + weights.epic + weights.prism
  local r = math.random() * total
  local acc = 0
  for _, key in ipairs({ "prism", "epic", "rare", "normal" }) do
    acc = acc + weights[key]
    if r <= acc then return M.RARITIES[key] end
  end
  return M.RARITIES.normal
end

function M.xpNeededForTier(tier)
  if tier == 1 then return 2 end
  if tier == 2 then return 4 end
  return 999
end

